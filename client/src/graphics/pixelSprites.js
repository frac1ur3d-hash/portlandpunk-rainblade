/**
 * Render an 8-bit sprite matrix onto an HTML5 2D Canvas context.
 */
export function drawPixelSprite(ctx, spriteRows, x, y, pixelSize = 3, flipX = false, flashColor = null) {
  if (!spriteRows || !spriteRows.length) return;
  const width = spriteRows[0].length;
  const height = spriteRows.length;

  ctx.save();
  ctx.imageSmoothingEnabled = false;

  for (let row = 0; row < height; row++) {
    const line = spriteRows[row];
    if (!line) continue;
    for (let col = 0; col < width; col++) {
      const char = line[col];
      if (char === '.' || !PALETTE[char]) continue;

      const color = flashColor || PALETTE[char];
      ctx.fillStyle = color;

      const drawCol = flipX ? (width - 1 - col) : col;
      const px = Math.floor(x + drawCol * pixelSize);
      const py = Math.floor(y + row * pixelSize);

      ctx.fillRect(px, py, pixelSize, pixelSize);
    }
  }

  ctx.restore();
}
